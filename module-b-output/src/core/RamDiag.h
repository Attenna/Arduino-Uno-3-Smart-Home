// ============================================
// RamDiag —— 栈高水位 / 空闲 RAM 诊断（issue #105）
// ============================================
// 为什么需要它：B 板的「反复重启」已定位到门/窗舵机负载（issue #104），但还有
// 一个未排除的候选——静态变量已占 81%（2048 里 1673），栈只剩 ~375 字节，深层
// 调用路径（如 system/selftest）可能**把栈压到堆上**，症状与「舵机供电欠压」完全
// 一样（都是重启 + 刷 ready），且固件读不到复位原因（optiboot 已清 MCUSR）。
//
// 做法：把「堆顶 → 当前 SP 下方 MARGIN」的空闲 RAM 涂成哨兵 0xC5。栈每往下压就
// 覆盖哨兵，于是**哨兵区与残迹的分界线就是本运行期栈的最深位置**。
//
// 关键技巧：AVR 复位**不清 SRAM**（启动只清 .bss / 初始化 .data，都在堆以下），
// 所以上一次运行期的涂色与残迹**跨复位保留** —— 只要在启动时（重新涂色之前）先
// 扫一遍，就能量出「崩掉那一次栈到底压到多深」，且无需写 EEPROM：
//   * hw     = 上一次/本次运行期栈最深用了多少字节（相对涂色区顶端）
//   * margin = 栈最深点距离堆顶还剩多少字节；**margin 到 0 就是栈压到堆上**（溢出）
#ifndef RAM_DIAG_H
#define RAM_DIAG_H

#include <stdint.h>

namespace RamDiag {

// setup() 最开头调用：先量「上一次运行期」的深度（读残迹），再重新涂色并清本次计数。
void begin();

// loop() 里低频调用（内部限频）：刷新本运行期的高水位/余量。
void update();

// 本次运行期的栈高水位（字节）。供 selftest 上报。
uint16_t stackHighWater();

// 上一次运行期（可能正是崩掉那次）的栈高水位（字节）。
uint16_t prevStackHighWater();

// 栈最深点距堆顶的剩余字节数（0 = 栈已经压到堆上）。本次运行期的实时值。
uint16_t stackMargin();

// 可测窗口大小（哨兵区字节数），判据要与它比较。
uint16_t stackWindow();

// 当前空闲 RAM（栈顶到堆顶之间还剩多少字节）。
uint16_t freeRam();

// 启动序号（EEPROM 持久化，只写 1 次/启动）。
uint16_t bootCount();

}  // namespace RamDiag

#endif  // RAM_DIAG_H